async function main(): Promise<void> {
  loadEnvLocal();
  const idRaw = process.env.SHEET_BOTLIB_ID;
  const saRaw = process.env.GOOGLE_SERVICE_ACCOUNT;
  if (!idRaw || !saRaw) {
    console.error("ต้องมี SHEET_BOTLIB_ID และ GOOGLE_SERVICE_ACCOUNT ใน env/.env.local");
    process.exit(1);
  }
  const spreadsheetId = idRaw.includes("/d/") ? /\/d\/([a-zA-Z0-9-_]+)/.exec(idRaw)![1] : idRaw.trim();
  const sa = JSON.parse(saRaw) as { client_email: string; private_key: string };
  const auth = new google.auth.JWT({ email: sa.client_email, key: sa.private_key.replace(/\\n/g, "\n"), scopes: ["https://www.googleapis.com/auth/spreadsheets"] });
  const sheets = google.sheets({ version: "v4", auth });

  const meta = await sheets.spreadsheets.get({ spreadsheetId });
  const existing = new Set((meta.data.sheets ?? []).map((s) => s.properties?.title ?? ""));
  console.log(`ไฟล์: ${meta.data.properties?.title} · แท็บที่มีอยู่: ${[...existing].join(", ") || "(ไม่มี)"}`);

  for (const tab of TABS) {
    if (existing.has(tab.title)) {
      console.log(`⏭  ข้าม "${tab.title}" — มีอยู่แล้ว (idempotent: ไม่เขียนทับ)`);
      continue;
    }
    await sheets.spreadsheets.batchUpdate({ spreadsheetId, requestBody: { requests: [{ addSheet: { properties: { title: tab.title } } }] } });
    await sheets.spreadsheets.values.update({
      spreadsheetId,
      range: `${tab.title}!A1`,
      valueInputOption: "RAW",
      requestBody: { values: tab.rows },
    });
    console.log(`✅ สร้าง "${tab.title}" + seed ${tab.rows.length} แถว`);
  }
  console.log("เสร็จ — เปิดไฟล์ตรวจ: แท็บวิธีใช้ (คำเตือน) · เส้นทางขาย S1-S4+S2Q · CSV_Config (เลขบัญชี placeholder ต้องกรอกจริงก่อน cutover)");
}

main().catch((e) => {
  console.error("seed ล้มเหลว:", e?.message ?? e);
  process.exit(1);
});
